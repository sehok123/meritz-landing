/**
 * 텍스트에서 욕설 포함 여부 체크
 * @param {string} text - 검사할 텍스트
 * @returns {boolean} 욕설이 없으면 true, 있으면 false
 */
function isCleanWords(text) {
    try {
        const inputLowerText = text.toLowerCase();
        return !badWords.some(word => inputLowerText === word.toLowerCase());
    } catch (error) {
        console.error(error);
        return false;
    }
}
